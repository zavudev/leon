//! What a program wrote around the person's words in the `user` role.
//!
//! Agents record as the person's whatever reached the model as a user turn,
//! and much of that is the harness's own: a background task that finished
//! (`<task-notification>`), a reminder, a command's output. A conversation
//! read back from the history shows it as a short note, not as something the
//! person said. The tags are the phone app's list (`mobile/src/chat/transcript.ts`),
//! drawn from real histories of Claude Code, Codex and opencode; tags of what
//! the person did put there (`pasted_content`, `image`) are not in it.
//!
//! Pure: text in, text out.

use std::sync::LazyLock;

use regex::Regex;

/// The harness's blocks: the pattern of the tag, and the name a note of it
/// goes by.
const TAGS: [(&str, &str); 14] = [
    ("task-notification", "task notification"),
    ("system-reminder", "system reminder"),
    ("command-(?:name|message|args|contents)", "command"),
    ("local-command-caveat", "command"),
    ("local-command-(?:stdout|stderr)", "command output"),
    ("bash-input", "shell command"),
    ("bash-(?:stdout|stderr)", "shell output"),
    ("user-prompt-submit-hook", "hook output"),
    ("environment_context|environment_details", "environment"),
    (
        "user_instructions|INSTRUCTIONS|permissions instructions",
        "instructions",
    ),
    ("recommended_plugins", "plugin list"),
    (
        "external_codex_apps_writing_block_edits(?:_part_\\d+_of_\\d+)?",
        "editor changes",
    ),
    ("in-app-browser-context", "browser context"),
    ("turn_aborted|user_action", "interruption"),
];

fn alternatives() -> String {
    TAGS.iter()
        .map(|(tag, _)| *tag)
        .collect::<Vec<_>>()
        .join("|")
}

/// One block of the harness, anywhere in a text. The regex crate has no
/// back-references, so the closing tag is matched as any of the list's.
static BLOCK: LazyLock<Regex> = LazyLock::new(|| {
    let tags = alternatives();
    Regex::new(&format!(r"(?s)<({tags})(?:\s[^<>]*)?>.*?</(?:{tags})>")).unwrap()
});

/// An entry that begins with a block which never closes: histories clip
/// long messages, and what is left of the block is still the harness's.
static CLIPPED: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(&format!(r"^<({})(?:\s[^<>]*)?>", alternatives())).unwrap());

/// Whole entries the harness writes without a tag.
static LINES: LazyLock<[(Regex, &'static str); 2]> = LazyLock::new(|| {
    [
        (
            Regex::new(r"^\[Request interrupted by user[^\]]*\]$").unwrap(),
            "interruption",
        ),
        (
            Regex::new(
                r"(?s)^Caveat: The messages below were generated by the user while running local commands\..*$",
            )
            .unwrap(),
            "command",
        ),
    ]
});

/// What a task notification says it is about: its `<summary>`, when it has one.
static SUMMARY: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?s)<summary>(.*?)</summary>").unwrap());

fn label_of(tag: &str) -> &'static str {
    TAGS.iter()
        .find(|(pattern, _)| {
            Regex::new(&format!("^(?:{pattern})$")).is_ok_and(|re| re.is_match(tag))
        })
        .map_or("system", |(_, label)| label)
}

/// A `user` entry, separated.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Split {
    /// What the person wrote, the harness's blocks taken out. Empty when none.
    pub said: String,
    /// The note for what the harness wrote: the kinds found, and a summary
    /// when a task notification gives one. `None` when it wrote nothing.
    pub note: Option<String>,
}

/// Separates what a person typed from what a program wrote around it.
pub fn split(text: &str) -> Split {
    let whole = text.trim();
    for (pattern, label) in LINES.iter() {
        if pattern.is_match(whole) {
            return Split {
                said: String::new(),
                note: Some((*label).to_owned()),
            };
        }
    }
    let mut labels: Vec<&'static str> = Vec::new();
    let mut summary = None;
    let said = BLOCK.replace_all(whole, |caps: &regex::Captures<'_>| {
        let label = label_of(&caps[1]);
        if !labels.contains(&label) {
            labels.push(label);
        }
        if summary.is_none() {
            summary = SUMMARY
                .captures(&caps[0])
                .map(|found| found[1].trim().to_owned());
        }
        String::new()
    });
    let said = Regex::new(r"\n{3,}")
        .unwrap()
        .replace_all(&said, "\n\n")
        .trim()
        .to_owned();
    if let Some(clipped) = CLIPPED.captures(&said) {
        let label = label_of(&clipped[1]);
        if !labels.contains(&label) {
            labels.insert(0, label);
        }
        return Split {
            said: String::new(),
            note: Some(note(&labels, summary.as_deref())),
        };
    }
    if labels.is_empty() {
        return Split {
            said: whole.to_owned(),
            note: None,
        };
    }
    Split {
        said,
        note: Some(note(&labels, summary.as_deref())),
    }
}

fn note(labels: &[&str], summary: Option<&str>) -> String {
    let kinds = labels.join(" + ");
    match summary.filter(|summary| !summary.is_empty()) {
        Some(summary) => format!("{kinds}: {summary}"),
        None => kinds,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_task_notification_is_a_note_with_its_summary_and_nothing_said() {
        let text = "<task-notification>\n<task-id>b1</task-id>\n<status>completed</status>\n<summary>Background command \"cargo test\" completed (exit code 0)</summary>\n</task-notification>";
        assert_eq!(
            split(text),
            Split {
                said: String::new(),
                note: Some(
                    "task notification: Background command \"cargo test\" completed (exit code 0)"
                        .into()
                ),
            }
        );
    }

    #[test]
    fn the_persons_words_stay_and_the_blocks_around_them_are_a_note() {
        let text = "<system-reminder>be brief</system-reminder>\n\nfix the build\n\n<bash-stdout>ok</bash-stdout>";
        assert_eq!(
            split(text),
            Split {
                said: "fix the build".into(),
                note: Some("system reminder + shell output".into()),
            }
        );
    }

    #[test]
    fn plain_words_and_the_persons_own_tags_are_left_alone() {
        assert_eq!(split(" hello ").said, "hello");
        assert_eq!(split(" hello ").note, None);
        let pasted = "<pasted_content>a log</pasted_content> look";
        assert_eq!(split(pasted).note, None);
    }

    #[test]
    fn a_clipped_block_and_the_lines_without_tags_are_the_harnesss() {
        assert_eq!(
            split("<task-notification>\n<task-id>b1</task-id> and then the history cut it"),
            Split {
                said: String::new(),
                note: Some("task notification".into()),
            }
        );
        assert_eq!(
            split("[Request interrupted by user for tool use]")
                .note
                .as_deref(),
            Some("interruption")
        );
    }
}
